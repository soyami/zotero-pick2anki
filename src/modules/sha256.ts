// ============ 纯 TS SHA-256 ============
// 为什么不用 WebCrypto：Edge TTS 的 Sec-MS-GEC 在拼接 URL 时同步需要哈希值，
// crypto.subtle 是异步 API；而插件沙箱里也不保证有 crypto。纯实现零环境依赖，
// 同时可被 anki.ts 复用来生成音频文件名（替代 Obsidian 版的 crypto.createHash("md5")）。

